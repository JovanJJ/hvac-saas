import assert from "node:assert/strict";
import { billingCommandSchema, handoverLink, readFilters } from "../../features/handover/model";
import { safeDestination } from "../../features/auth/validation";
const id = "a1000000-0000-4000-8000-000000000001";
assert.equal(readFilters({}).filters.state, "missing");
assert.equal(readFilters({ queue: "billing" }).filters.state, "pending");
assert.equal(readFilters({ queue: "billing", state: "missing" }).invalid, true);
assert.equal(readFilters({ from: "2026-12-01", until: "2026-01-01" }).invalid, true);
assert.equal(readFilters({ from: "2026-02-30" }).invalid, true);
assert.equal(readFilters({ page: "10001" }).invalid, true);
const filters = readFilters({ site: [id], customer: id, state: "received", from: "2026-11-01", revision: "latest" }).filters;
const url = new URL(handoverLink(filters, { page: 2 }), "https://example.invalid");
assert.equal(url.searchParams.get("site"), id);
assert.equal(url.searchParams.get("revision"), "latest");
assert.equal(url.searchParams.get("from"), "2026-11-01");
assert.equal(url.searchParams.get("page"), "2");
const command = { visitId: id, operationId: id, version: "0", visitVersion: "1", ready: "true", note: " Fictional review " };
assert.equal(billingCommandSchema.parse(command).note, "Fictional review");
assert.equal(billingCommandSchema.safeParse({ ...command, note: " " }).success, false);
assert.equal(billingCommandSchema.safeParse({ ...command, ready: "yes" }).success, false);
assert.equal(safeDestination(`/office/handover/${id}`), `/office/handover/${id}`);
assert.equal(safeDestination(`/office/handover/${id}/../../settings`), "/account");
assert.equal(safeDestination("/office/handover"), "/office/handover");
